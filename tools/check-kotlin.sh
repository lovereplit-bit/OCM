#!/usr/bin/env bash
# Type-checks the Kotlin sources against the Android SDK jar without Gradle.
# Usage: tools/check-kotlin.sh [path-to-android.jar] [path-to-kotlinc]
# A stub R class is generated from res/ so missing resource names are reported too.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
jar="${1:-${ANDROID_JAR:-/tmp/tools/android-platforms/android-35/android.jar}}"
kotlinc="${2:-${KOTLINC:-kotlinc}}"
res="$root/android/app/src/main/res"
src="$root/android/app/src/main/kotlin"
out="$(mktemp -d)"

trap 'rm -rf "$out"' EXIT

python3 - "$res" "$out/R.kt" <<'PY'
import os, re, sys
res, target = sys.argv[1], sys.argv[2]
ids = {}
def add(kind, name):
    ids.setdefault(kind, set()).add(name.replace('.', '_'))
for entry in sorted(os.listdir(res)):
    path = os.path.join(res, entry)
    if not os.path.isdir(path):
        continue
    kind = entry.split('-')[0]
    for f in os.listdir(path):
        if kind == 'values':
            text = open(os.path.join(path, f), encoding='utf-8').read()
            for tag, k in (('string', 'string'), ('color', 'color'), ('dimen', 'dimen'), ('style', 'style'), ('bool', 'bool'), ('integer', 'integer')):
                for m in re.finditer(r'<%s\s+name="([^"]+)"' % tag, text):
                    add(k, m.group(1))
        else:
            add(kind, os.path.splitext(f)[0])
            # Ids are declared with @+id inside layouts and menus, not in a file of their own.
            if f.endswith('.xml'):
                text = open(os.path.join(path, f), encoding='utf-8').read()
                for m in re.finditer(r'@\+id/([A-Za-z0-9_]+)', text):
                    add('id', m.group(1))
with open(target, 'w') as out:
    out.write('package dev.opencode.mobile\n\nobject R {\n')
    for kind, names in sorted(ids.items()):
        out.write('    object %s {\n' % kind)
        for n in sorted(names):
            out.write('        const val %s = 0\n' % n)
        out.write('    }\n')
    out.write('}\n')
PY

echo "R stub: $(grep -c 'const val' "$out/R.kt") resource ids"

# BuildConfig is generated by Gradle; this stub carries the same fields.
cat > "$out/BuildConfig.kt" <<'KT'
package dev.opencode.mobile

object BuildConfig {
    const val DEBUG = false
    const val VERSION_NAME = "0.0.0"
    const val VERSION_CODE = 1
    const val UPSTREAM_REF = "stub"
    const val UPSTREAM_VERSION = "0.0.0"
    const val RUNTIME_SEQ = 0L
    const val OTA_REPO = "owner/repo"
    const val WEBVIEW_DEBUG = false
}
KT

if "$kotlinc" -nowarn -jvm-target 17 -classpath "$jar" -d "$out/classes" "$out/R.kt" "$out/BuildConfig.kt" $(find "$src" -name '*.kt') >"$out/log" 2>&1; then
    echo "kotlinc: OK ($(find "$src" -name '*.kt' | wc -l) files)"
else
    grep -v '^warning:' "$out/log" || true
    echo "kotlinc: FAILED"
    exit 1
fi
